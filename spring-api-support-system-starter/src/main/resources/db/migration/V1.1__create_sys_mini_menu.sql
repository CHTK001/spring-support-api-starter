CREATE TABLE IF NOT EXISTS `sys_mini_menu` (
  `sys_mini_menu_id` int(11) NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `sys_mini_menu_title` varchar(255) DEFAULT NULL COMMENT '卡片标题',
  `sys_mini_menu_subtitle` varchar(255) DEFAULT NULL COMMENT '卡片副标题',
  `sys_mini_menu_category` varchar(128) DEFAULT NULL COMMENT '卡片分组',
  `sys_mini_menu_path` varchar(255) DEFAULT NULL COMMENT '小程序页面路径',
  `sys_mini_menu_jump_mode` int(11) DEFAULT 0 COMMENT '跳转模式;0:普通页面 1:tabBar页面 2:webview',
  `sys_mini_menu_icon` varchar(255) DEFAULT NULL COMMENT '卡片图标',
  `sys_mini_menu_cover` varchar(255) DEFAULT NULL COMMENT '卡片封面/背景',
  `sys_mini_menu_badge` varchar(64) DEFAULT NULL COMMENT '角标文案',
  `sys_mini_menu_badge_type` varchar(64) DEFAULT NULL COMMENT '角标样式',
  `sys_mini_menu_perm` varchar(255) DEFAULT NULL COMMENT '权限标识',
  `sys_mini_menu_role` varchar(255) DEFAULT NULL COMMENT '所属角色编码',
  `sys_mini_menu_sort` int(11) DEFAULT 1 COMMENT '排序优先级',
  `sys_mini_menu_keep_alive` int(11) DEFAULT 0 COMMENT '是否缓存；0:否',
  `sys_mini_menu_hidden` int(11) DEFAULT 0 COMMENT '是否隐藏；0:显示',
  `sys_mini_menu_description` varchar(255) DEFAULT NULL COMMENT '卡片说明',
  `create_name` varchar(255) DEFAULT NULL COMMENT '创建人姓名',
  `create_by` int(11) DEFAULT NULL COMMENT '创建人',
  `create_time` datetime DEFAULT NULL COMMENT '创建时间',
  `update_time` datetime DEFAULT NULL COMMENT '更新时间',
  `update_name` varchar(255) DEFAULT NULL COMMENT '更新人姓名',
  `update_by` int(11) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`sys_mini_menu_id`) USING BTREE,
  KEY `idx_mini_menu_sort` (`sys_mini_menu_sort`) USING BTREE,
  KEY `idx_mini_menu_perm` (`sys_mini_menu_perm`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='小程序菜单卡片表' ROW_FORMAT=DYNAMIC;
