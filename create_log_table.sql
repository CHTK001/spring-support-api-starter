CREATE TABLE IF NOT EXISTS system_server_log (
    system_server_log_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
    system_server_log_server_id INT DEFAULT NULL COMMENT '关联 system_server.system_server_id',
    system_server_log_filter_type VARCHAR(255) DEFAULT NULL COMMENT '过滤器类型',
    system_server_log_action_status VARCHAR(16) DEFAULT NULL COMMENT '通行/拒绝',
    system_server_log_process_status VARCHAR(255) DEFAULT NULL COMMENT '处理结果状态',
    system_server_log_client_ip VARCHAR(255) DEFAULT NULL COMMENT '客户端 IP',
    system_server_log_client_geo VARCHAR(255) DEFAULT NULL COMMENT '客户端地理位置',
    system_server_log_user_agent VARCHAR(1000) DEFAULT NULL COMMENT 'User-Agent',
    system_server_log_request_id VARCHAR(128) DEFAULT NULL COMMENT '请求ID',
    system_server_log_method VARCHAR(32) DEFAULT NULL COMMENT '请求方法',
    system_server_log_path VARCHAR(1000) DEFAULT NULL COMMENT '路径',
    system_server_log_rule_category VARCHAR(32) DEFAULT NULL COMMENT '规则分类',
    system_server_log_decision_reason VARCHAR(2000) DEFAULT NULL COMMENT '命中原因',
    system_server_log_access_time TIMESTAMP NULL DEFAULT NULL COMMENT '请求进入时间',
    system_server_log_duration_ms BIGINT DEFAULT NULL COMMENT '处理耗时',
    system_server_log_store_time TIMESTAMP NULL DEFAULT NULL COMMENT '落库时间',
    create_name VARCHAR(255) DEFAULT NULL,
    create_by INT DEFAULT NULL,
    create_time TIMESTAMP NULL DEFAULT NULL,
    update_time TIMESTAMP NULL DEFAULT NULL,
    update_name VARCHAR(255) DEFAULT NULL,
    update_by INT DEFAULT NULL,
    PRIMARY KEY (system_server_log_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='系统服务器过滤器访问与处理日志';
