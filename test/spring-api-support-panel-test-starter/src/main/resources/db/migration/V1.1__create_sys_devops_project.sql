CREATE TABLE IF NOT EXISTS sys_devops_project (
    project_id            BIGINT        NOT NULL AUTO_INCREMENT PRIMARY KEY,
    project_name          VARCHAR(100)  NOT NULL,
    project_description   TEXT          NULL,
    project_icon          VARCHAR(255)  NULL,
    server_os             VARCHAR(10)   NULL DEFAULT 'unknown',
    sort_order            INT           NOT NULL DEFAULT 0,
    status                TINYINT       NOT NULL DEFAULT 1,
    server_type           VARCHAR(10)   NULL,
    server_host           VARCHAR(512)  NULL,
    server_port           INT           NULL,
    server_username       VARCHAR(512)  NULL,
    server_password       VARCHAR(1024) NULL,
    server_private_key    TEXT          NULL,
    server_connect_timeout INT          NOT NULL DEFAULT 30,
    server_enabled        TINYINT       NOT NULL DEFAULT 0,
    server_activated_at   DATETIME      NULL,
    log_path              VARCHAR(512)  NULL,
    config_path           VARCHAR(512)  NULL,
    lib_path              VARCHAR(512)  NULL,
    root_path             VARCHAR(512)  NULL,
    start_script          TEXT          NULL,
    stop_script           TEXT          NULL,
    restart_script        TEXT          NULL,
    create_time           DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time           DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_by             VARCHAR(64)   NULL,
    update_by             VARCHAR(64)   NULL
);
