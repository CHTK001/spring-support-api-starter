-- H2兼容的定时任务模块初始化SQL (MySQL模式)
-- 移除了MySQL特有的 ENGINE, CHARACTER SET, COLLATE, SET NAMES 等语法

CREATE TABLE IF NOT EXISTS `sys_job` (
    `job_id` INT NOT NULL AUTO_INCREMENT COMMENT '任务ID',
    `job_no` VARCHAR(64) NOT NULL COMMENT '任务编号',
    `job_name` VARCHAR(255) DEFAULT NULL COMMENT '任务名称',
    `job_schedule_type` VARCHAR(50) DEFAULT 'CRON' COMMENT '调度类型',
    `job_schedule_time` VARCHAR(255) DEFAULT NULL COMMENT '调度配置',
    `job_author` VARCHAR(100) DEFAULT NULL COMMENT '负责人',
    `job_alarm_email` VARCHAR(255) DEFAULT NULL COMMENT '报警邮件',
    `job_group` VARCHAR(100) DEFAULT NULL COMMENT '任务分组',
    `job_trigger_status` TINYINT DEFAULT 0 COMMENT '调度状态',
    `job_desc` VARCHAR(500) DEFAULT NULL COMMENT '任务描述',
    `job_glue_updatetime` DATETIME DEFAULT NULL COMMENT 'GLUE更新时间',
    `job_glue_source` TEXT DEFAULT NULL COMMENT 'GLUE源码',
    `job_glue_type` VARCHAR(50) DEFAULT 'BEAN' COMMENT 'GLUE类型',
    `job_dispatch_mode` VARCHAR(20) DEFAULT 'LOCAL' COMMENT '分发模式',
    `job_remote_executor_address` VARCHAR(500) DEFAULT NULL COMMENT '远程执行器地址',
    `job_storage_mode` VARCHAR(20) DEFAULT 'DATABASE' COMMENT '存储模式',
    `job_fail_retry` INT DEFAULT 3 COMMENT '失败重试次数',
    `job_retry_interval` INT DEFAULT 0 COMMENT '失败重试间隔(秒)',
    `job_execute_timeout` INT DEFAULT 0 COMMENT '执行超时时间(秒)',
    `job_execute_bean` VARCHAR(255) DEFAULT NULL COMMENT '执行器处理器名称',
    `job_execute_param` VARCHAR(512) DEFAULT NULL COMMENT '执行参数',
    `job_exception_callback_bean` VARCHAR(255) DEFAULT NULL COMMENT '异常回调处理器',
    `job_retry_callback_bean` VARCHAR(255) DEFAULT NULL COMMENT '重试前回调处理器',
    `job_execute_misfire_strategy` VARCHAR(50) DEFAULT 'DO_NOTHING' COMMENT '错失策略',
    `job_trigger_last_time` BIGINT DEFAULT 0 COMMENT '上次调度时间',
    `job_trigger_next_time` BIGINT DEFAULT 0 COMMENT '下次调度时间',
    `is_deleted` TINYINT DEFAULT 0 COMMENT '逻辑删除标记',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '更新时间',
    `create_by` VARCHAR(50) DEFAULT NULL COMMENT '创建人',
    `update_by` VARCHAR(50) DEFAULT NULL COMMENT '更新人',
    PRIMARY KEY (`job_id`)
);

CREATE TABLE IF NOT EXISTS `sys_job_log` (
    `job_log_id` INT NOT NULL AUTO_INCREMENT COMMENT '日志ID',
    `job_log_no` VARCHAR(64) NOT NULL COMMENT '日志编号',
    `job_id` INT DEFAULT NULL COMMENT '任务ID',
    `job_no` VARCHAR(64) DEFAULT NULL COMMENT '任务编号',
    `job_log_app` VARCHAR(255) DEFAULT NULL COMMENT '触发应用',
    `job_log_trigger_bean` VARCHAR(255) DEFAULT NULL COMMENT '执行器处理器名称',
    `job_log_trigger_type` VARCHAR(50) DEFAULT NULL COMMENT '触发类型',
    `job_log_profile` VARCHAR(50) DEFAULT NULL COMMENT '环境',
    `job_log_trigger_time` DATETIME DEFAULT NULL COMMENT '触发时间',
    `job_log_trigger_date` DATE DEFAULT NULL COMMENT '触发日期',
    `job_log_trigger_code` VARCHAR(20) DEFAULT NULL COMMENT '触发状态',
    `job_log_execute_code` VARCHAR(20) DEFAULT 'PADDING' COMMENT '执行状态',
    `job_log_cost` DECIMAL(10, 2) DEFAULT NULL COMMENT '执行耗时(ms)',
    `job_log_trigger_msg` TEXT DEFAULT NULL COMMENT '触发消息',
    `job_log_trigger_param` VARCHAR(512) DEFAULT NULL COMMENT '触发参数',
    `job_log_trigger_address` VARCHAR(255) DEFAULT NULL COMMENT '触发地址',
    `job_log_file_path` VARCHAR(500) DEFAULT NULL COMMENT '日志文件路径',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '更新时间',
    `create_by` VARCHAR(50) DEFAULT NULL COMMENT '创建人',
    `update_by` VARCHAR(50) DEFAULT NULL COMMENT '更新人',
    PRIMARY KEY (`job_log_id`)
);

CREATE TABLE IF NOT EXISTS `sys_job_log_detail` (
    `job_log_detail_id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '日志详情ID',
    `job_log_id` INT DEFAULT NULL COMMENT '关联的任务日志ID',
    `job_log_no` VARCHAR(64) DEFAULT NULL COMMENT '关联的任务日志编号',
    `job_id` INT DEFAULT NULL COMMENT '任务ID',
    `job_no` VARCHAR(64) DEFAULT NULL COMMENT '任务编号',
    `job_log_detail_level` VARCHAR(20) DEFAULT 'INFO' COMMENT '日志级别',
    `job_log_detail_content` TEXT DEFAULT NULL COMMENT '日志内容',
    `job_log_detail_time` DATETIME DEFAULT NULL COMMENT '日志时间戳',
    `job_log_detail_phase` VARCHAR(50) DEFAULT NULL COMMENT '执行阶段',
    `job_log_detail_progress` INT DEFAULT NULL COMMENT '执行进度',
    `job_log_detail_file_path` VARCHAR(500) DEFAULT NULL COMMENT '日志文件路径',
    `job_log_detail_handler` VARCHAR(255) DEFAULT NULL COMMENT '执行的方法/Handler名',
    `job_log_detail_profile` VARCHAR(100) DEFAULT NULL COMMENT '执行环境/Profile',
    `job_log_detail_address` VARCHAR(255) DEFAULT NULL COMMENT '执行地址',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (`job_log_detail_id`)
);

CREATE TABLE IF NOT EXISTS `sys_job_log_backup` (
    `job_log_backup_id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '备份记录ID',
    `job_log_backup_file_name` VARCHAR(255) DEFAULT NULL COMMENT '备份文件名',
    `job_log_backup_file_path` VARCHAR(500) DEFAULT NULL COMMENT '备份文件路径',
    `job_log_backup_file_size` BIGINT DEFAULT NULL COMMENT '备份文件大小(字节)',
    `job_log_backup_count` BIGINT DEFAULT NULL COMMENT '备份日志条数',
    `job_log_backup_start_date` DATE DEFAULT NULL COMMENT '备份日志开始日期',
    `job_log_backup_end_date` DATE DEFAULT NULL COMMENT '备份日志结束日期',
    `job_log_backup_status` VARCHAR(20) DEFAULT 'RUNNING' COMMENT '备份状态',
    `job_log_backup_type` VARCHAR(20) DEFAULT 'MANUAL' COMMENT '备份类型',
    `job_log_backup_start_time` DATETIME DEFAULT NULL COMMENT '备份开始时间',
    `job_log_backup_end_time` DATETIME DEFAULT NULL COMMENT '备份完成时间',
    `job_log_backup_cost` BIGINT DEFAULT NULL COMMENT '备份耗时(毫秒)',
    `job_log_backup_message` VARCHAR(1000) DEFAULT NULL COMMENT '备份消息/错误信息',
    `job_log_backup_compress_type` VARCHAR(20) DEFAULT 'ZIP' COMMENT '压缩格式',
    `job_log_backup_cleaned` TINYINT DEFAULT 0 COMMENT '是否已删除原始日志',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (`job_log_backup_id`)
);
